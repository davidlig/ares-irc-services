#[CoversNothing]
final class RescueCredentialFlowTest extends DoctrineIntegrationTestCase
{
    #[Test]
    public function realSqlOnboardingMigrationAndRecovery(): void
    {
        $now = new DateTimeImmutable('2026-10-21T12:00:00Z');
        $db = $this->entityManager->getConnection();
        self::assertArrayNotHasKey('registration_mode', $db->createSchemaManager()->listTableColumns('registered_nicks'));
        $repo = new RegisteredNickDoctrineRepository($this->entityManager);
        $history = new NickHistoryService(new NickHistoryDoctrineRepository($this->entityManager));
        $regrepo = new DoctrineRegisterNickRepository($this->entityManager);
        $cas = new DoctrineRescueCredentialPersistence($this->entityManager);
        $policy = new DoctrineRegistrationPolicyRepository($db);
        $codec = new UuidRescueTokenCodec();
        $temp = new InMemoryTemporaryRescueTokenStore();
        $limiter = new InMemoryRescueAttemptLimiter();
        $sessions = new IdentifiedSessionRegistry();
        $clock = $this->createStub(Clock::class);
        $clock->method('now')->willReturnCallback(static function () use (&$now): DateTimeImmutable { return $now; });
        $hasher = $this->createStub(PasswordHasher::class);
        $hasher->method('hash')->willReturnCallback(static fn (string $s): string => 'hash:' . $s);
        $throttle = $this->createStub(RegistrationThrottle::class);
        $throttle->method('remainingCooldownSeconds')->willReturn(0);
        $mail = $this->createMock(RegistrationMailSender::class);
        $mailToken = null;
        $mail->expects(self::once())->method('sendVerification')->willReturnCallback(static function (string $nick, string $email, string $token) use (&$mailToken): void {$mailToken = $token; });
        $emailPolicy = new OperServEmailDomainPolicy(new BadmailEmailPolicy(new DoctrineBadmailRepository($this->entityManager)));
        $register = new RegisterNickHandler($emailPolicy, $regrepo, $hasher, $codec, $clock, $temp, $policy, $throttle, $mail, 0);
        $events = $this->createMock(RegistrationEventPublisher::class);
        $events->expects(self::exactly(2))->method('publish');
        $auth = $this->createStub(NicknameAuthenticationModeQuery::class);
        $auth->method('current')->willReturn(NicknameAuthenticationMode::ServiceCommand);
        $makeVerify = static fn (TemporaryRescueTokenStore $store): VerifyNickHandler => new VerifyNickHandler($repo, $codec, $store, $limiter, $cas, $sessions, $clock, $auth, $events, $history);
        $verify = $makeVerify($temp);
        $digest = static fn () => hash('sha256', serialize($db->fetchAllAssociative('SELECT * FROM registered_nicks ORDER BY id')));
        $result = $register->handle(new RegisterNick('Token', 'password', null, 'en', 'clientA'));
        self::assertSame(RegisterNickOutcome::TokenVerificationRequired, $result->outcome);
        $token = $result->token;
        self::assertNotNull($token);
        $account = $repo->findByNick('Token');
        self::assertNotNull($account);
        self::assertNull($db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$account->getId()]));
        self::assertNull($account->getEmail());
        self::assertTrue($account->isPending());
        $before = $digest();
        $register->handle(new RegisterNick('Token', 'another', null, 'en', 'clientA'));
        self::assertSame($before, $digest());
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Token', 'wrong', 'UID', 'Token', clientKey: 'clientA'))->outcome);
        self::assertSame($before, $digest());
        self::assertSame(VerifyNickOutcome::Success, $verify->handle(new VerifyNick('Token', $token, 'UID', 'Token', clientKey: 'clientA'))->outcome);
        self::assertSame($codec->hash($token), $db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$account->getId()]));
        self::assertTrue($account->isRegistered());
        $pw = $this->createStub(RecoveryPasswordGenerator::class);
        $pw->method('generate')->willReturn('replacement-password');
        $revents = $this->createMock(RecoverEventPublisher::class);
        $revents->expects(self::exactly(4))->method('publish');
        $recoveryMailToken = null;
        $recoveryMailer = $this->createMock(RecoveryMailSender::class);
        $recoveryMailer->expects(self::once())->method('sendRecovery')->willReturnCallback(static function (string $nick, string $email, string $token) use (&$recoveryMailToken): void {
            $recoveryMailToken = $token;
        });
        $recoveryRegistry = new RecoveryTokenRegistry();
        $recover = new RecoverNickHandler($repo, $hasher, $pw, $codec, $cas, $revents, $clock, $policy, $recoveryRegistry, $recoveryMailer, $limiter, $temp);
        $before = $digest();
        $recover->handle(new RecoverNick('Token'));
        self::assertSame($before, $digest());
        $reset = $recover->handle(new RecoverNick('Token', $token, clientKey: 'clientA'));
        self::assertSame(RecoverNickOutcome::PasswordReset, $reset->outcome);
        self::assertSame('hash:replacement-password', $account->getPasswordHash());
        self::assertNotNull($reset->rescueToken);
        self::assertSame($codec->hash($token), $account->getRescueTokenHash());
        self::assertTrue($temp->matches($account->getId(), (string) $codec->hash($reset->rescueToken), $now));
        $beforeOptional = $digest();
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Token', $reset->rescueToken, 'FOREIGN', 'Token', clientKey: 'clientX'))->outcome);
        self::assertSame($beforeOptional, $digest());
        self::assertSame($codec->hash($token), $account->getRescueTokenHash());
        self::assertSame(VerifyNickOutcome::CredentialConfirmed, $verify->handle(new VerifyNick('Token', $reset->rescueToken, 'UID', 'Token', clientKey: 'clientA'))->outcome);
        self::assertSame($codec->hash($reset->rescueToken), $account->getRescueTokenHash());
        $before = $digest();
        self::assertSame(RecoverNickOutcome::InvalidToken, $recover->handle(new RecoverNick('Token', $token, clientKey: 'clientA'))->outcome);
        self::assertSame($before, $digest());
        $policy->change(RegistrationMode::Email);
        $register->handle(new RegisterNick('Mail', 'password', 'mail@example.test', 'en', 'clientB'));
        $mailAccount = $repo->findByNick('Mail');
        self::assertNotNull($mailAccount);
        self::assertNotNull($mailToken);
        self::assertNull($mailAccount->getRescueTokenHash());
        // A later block must not lock a pending/existing account out of verification or recovery.
        $db->insert('operserv_badmail', ['domain' => 'example.test', 'reason' => 'blocked after registration']);
        self::assertTrue($emailPolicy->isBlocked('mail@example.test'));
        $beforeBlockedRetry = $digest();
        self::assertSame(RegisterNickOutcome::BlockedEmailDomain, $register->handle(new RegisterNick('Mail', 'another', 'mail@example.test', 'en', 'clientB'))->outcome);
        self::assertSame($beforeBlockedRetry, $digest());
        $resendThrottle = $this->createStub(ResendThrottle::class);
        $resendThrottle->method('remainingCooldownSeconds')->willReturn(0);
        $resendMail = $this->createMock(ResendMailSender::class);
        $resentToken = null;
        $resendMail->expects(self::once())->method('sendResend')->willReturnCallback(static function (string $n, string $e, string $t) use (&$resentToken): void {$resentToken = $t; });
        $resend = new ResendVerificationHandler($repo, $resendThrottle, $codec, $temp, $policy, $resendMail, $clock, $history, 600);
        $originalDeadline = $mailAccount->getExpiresAt();
        $now = $now->modify('+59 minutes');
        $resend->handle(new ResendVerification('Mail', 'en', 'Oper'));
        self::assertSame($now->modify('+1 hour')->format('c'), $mailAccount->getExpiresAt()?->format('c'));
        $persistedExpiry = $db->fetchOne('SELECT expires_at FROM registered_nicks WHERE id=?', [$mailAccount->getId()]);
        self::assertIsString($persistedExpiry);
        self::assertSame($mailAccount->getExpiresAt()->getTimestamp(), new DateTimeImmutable($persistedExpiry)->getTimestamp());
        $pendingDigest = $digest();
        self::assertNotNull($resentToken);
        self::assertNotSame($mailToken, $resentToken);
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Mail', $mailToken, 'MAILUID', 'Mail', clientKey: 'clientB'))->outcome);
        self::assertSame($pendingDigest, $digest());
        $mailToken = $resentToken;
        $now = $now->modify('+2 minutes');
        self::assertNotNull($originalDeadline);
        self::assertGreaterThan($originalDeadline->getTimestamp(), $now->getTimestamp());
        $this->entityManager->clear();
        // Unconfirmed EMAIL tokens are memory-only too; restart cannot promote them.
        self::assertSame(VerifyNickOutcome::InvalidToken, $makeVerify(new InMemoryTemporaryRescueTokenStore())->handle(new VerifyNick('Mail', $mailToken, 'MAILUID', 'Mail', clientKey: 'clientB'))->outcome);
        self::assertSame(VerifyNickOutcome::Success, $verify->handle(new VerifyNick('Mail', $mailToken, 'MAILUID', 'Mail', clientKey: 'clientB'))->outcome);
        $mailAccount = $repo->findByNick('Mail');
        self::assertNotNull($mailAccount);
        $before = $digest();
        $request = $recover->handle(new RecoverNick('Mail', clientKey: 'clientB'));
        self::assertSame(RecoverNickOutcome::TokenSent, $request->outcome);
        self::assertSame($before, $digest());
        self::assertNotNull($recoveryMailToken);
        self::assertSame($codec->hash($mailToken), $mailAccount->getRescueTokenHash());
        $policy->change(RegistrationMode::Token);
        self::assertSame(RecoverNickOutcome::Instructions, $recover->handle(new RecoverNick('Mail', clientKey: 'clientB'))->outcome);
        self::assertSame($before, $digest());
        $recoveryRegistry->store('Mail', $recoveryMailToken, $now);
        self::assertSame(RecoverNickOutcome::InvalidToken, $recover->handle(new RecoverNick('Mail', $recoveryMailToken, clientKey: 'clientB'))->outcome);
        self::assertSame($before, $digest());
        $recoveryRegistry->store('Mail', $recoveryMailToken, $now->modify('+1 hour'));
        $promoted = $recover->handle(new RecoverNick('Mail', $recoveryMailToken, clientKey: 'clientB'));
        self::assertSame(RecoverNickOutcome::PasswordReset, $promoted->outcome);
        self::assertTrue($promoted->tokenPromoted);
        self::assertSame($recoveryMailToken, $promoted->rescueToken);
        self::assertSame($codec->hash($recoveryMailToken), $mailAccount->getRescueTokenHash());
        self::assertFalse($temp->matches($mailAccount->getId(), (string) $codec->hash($mailToken), $now));
        $legacy = RegisteredNick::createPending('Legacy', 'hash:old', 'legacy@example.test', 'en', $now->modify('+1 hour'), $now);
        $legacy->activate();
        $repo->save($legacy);
        $issued = [];
        $notifier = $this->createMock(RescueTokenNotifier::class);
        $notifier->expects(self::exactly(2))->method('issued')->willReturnCallback(static function (string $uid, string $t) use (&$issued): void {$issued[] = $t; });
        $issue = new IssueMigrationRescueTokenHandler($repo, $codec, $temp, $notifier);
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(), 'LEGACYUID', $now));
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(), 'LEGACYUID', $now));
        self::assertNull($db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$legacy->getId()]));
        $before = $digest();
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Legacy', $issued[1], 'FOREIGN', 'Legacy', clientKey: 'clientC'))->outcome);
        self::assertSame($before, $digest());
        $sessions->register('LEGACYUID', 'Legacy');
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Legacy', $issued[0], 'LEGACYUID', 'Legacy', clientKey: 'clientC'))->outcome);
        self::assertSame($before, $digest());
        self::assertSame(VerifyNickOutcome::CredentialConfirmed, $verify->handle(new VerifyNick('Legacy', $issued[1], 'LEGACYUID', 'Legacy', clientKey: 'clientC'))->outcome);
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(), 'LEGACYUID', $now));
        self::assertSame($codec->hash($issued[1]), $legacy->getRescueTokenHash());
    }
}
