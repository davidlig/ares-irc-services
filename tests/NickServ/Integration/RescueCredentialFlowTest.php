use App\NickServ\Domain\Entity\RegisteredNick;
use App\NickServ\Domain\ValueObject\RegistrationMode;
use App\Tests\Shared\DoctrineIntegrationTestCase;
use DateTimeImmutable;
use PHPUnit\Framework\Attributes\CoversNothing;

#[CoversNothing]
final class RescueCredentialFlowTest extends DoctrineIntegrationTestCase
{
    public function testRealSqlOnboardingMigrationAndRecovery(): void
    {
        $now = new DateTimeImmutable('2026-10-21T12:00:00Z');
        $db = $this->entityManager->getConnection();
        $repo = new RegisteredNickDoctrineRepository($this->entityManager);
        $regrepo = new DoctrineRegisterNickRepository($this->entityManager);
        $cas = new DoctrineRescueCredentialPersistence($this->entityManager);
        $policy = new DoctrineRegistrationPolicyRepository($db);
        $codec = new UuidRescueTokenCodec();
        $temp = new InMemoryTemporaryRescueTokenStore();
        $limiter = new InMemoryRescueAttemptLimiter();
        $sessions = new IdentifiedSessionRegistry();
        $clock = $this->createStub(Clock::class);
        $clock->method('now')->willReturn($now);
        $hasher = $this->createStub(PasswordHasher::class);
        $hasher->method('hash')->willReturnCallback(static fn (string $s): string => 'hash:' . $s);
        $throttle = $this->createStub(RegistrationThrottle::class);
        $throttle->method('remainingCooldownSeconds')->willReturn(0);
        $mail = $this->createMock(RegistrationMailSender::class);
        $mailToken = null;
        $mail->expects(self::once())->method('sendVerification')->willReturnCallback(static function (string $nick, string $email, string $token) use (&$mailToken): void {$mailToken = $token; });
        $register = new RegisterNickHandler($regrepo, $hasher, $codec, $clock, $temp, $policy, $throttle, $mail, 0);
        $events = $this->createMock(RegistrationEventPublisher::class);
        $events->expects(self::exactly(2))->method('publish');
        $auth = $this->createStub(NicknameAuthenticationModeQuery::class);
        $auth->method('current')->willReturn(NicknameAuthenticationMode::ServiceCommand);
        $makeVerify = static fn (TemporaryRescueTokenStore $store): VerifyNickHandler => new VerifyNickHandler($repo, $codec, $store, $limiter, $cas, $sessions, $clock, $auth, $events);
        $verify = $makeVerify($temp);
        $digest = static fn () => hash('sha256', serialize($db->fetchAllAssociative('SELECT * FROM registered_nicks ORDER BY id')));
        $result = $register->handle(new RegisterNick('Token', 'password', null, 'en', 'clientA'));
        self::assertSame(RegisterNickOutcome::TokenVerificationRequired, $result->outcome);
        $token = $result->token;
        self::assertNotNull($token);
        $account = $repo->findByNick('Token');
        self::assertNotNull($account);
        self::assertNull($db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$account->getId()]));
        self::assertNull($account->getEmail());
        self::assertTrue($account->isPending());
        $before = $digest();
        $register->handle(new RegisterNick('Token', 'another', null, 'en', 'clientA'));
        self::assertSame($before, $digest());
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Token', 'wrong', 'UID', 'clientA'))->outcome);
        self::assertSame($before, $digest());
        self::assertSame(VerifyNickOutcome::Success, $verify->handle(new VerifyNick('Token', $token, 'UID', 'clientA'))->outcome);
        self::assertSame($codec->hash($token), $db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$account->getId()]));
        self::assertTrue($account->isRegistered());
        $validator = new ValidateRescueTokenHandler($repo, $codec, $limiter, $clock);
        $pw = $this->createStub(RecoveryPasswordGenerator::class);
        $pw->method('generate')->willReturn('replacement-password');
        $revents = $this->createMock(RecoverEventPublisher::class);
        $revents->expects(self::exactly(2))->method('publish');
        $recover = new RecoverNickHandler($repo, $hasher, $pw, $validator, $codec, $cas, $revents, $clock);
        $before = $digest();
        $recover->handle(new RecoverNick('Token'));
        self::assertSame($before, $digest());
        $reset = $recover->handle(new RecoverNick('Token', $token, clientKey: 'clientA'));
        self::assertSame(RecoverNickOutcome::PasswordReset, $reset->outcome);
        self::assertSame('hash:replacement-password', $account->getPasswordHash());
        self::assertNotNull($reset->rescueToken);
        self::assertSame($codec->hash($reset->rescueToken), $account->getRescueTokenHash());
        $before = $digest();
        self::assertSame(RecoverNickOutcome::InvalidToken, $recover->handle(new RecoverNick('Token', $token, clientKey: 'clientA'))->outcome);
        self::assertSame($before, $digest());
        $policy->change(RegistrationMode::Email);
        $register->handle(new RegisterNick('Mail', 'password', 'mail@example.test', 'en', 'clientB'));
        $mailAccount = $repo->findByNick('Mail');
        self::assertNotNull($mailAccount);
        self::assertNotNull($mailToken);
        self::assertSame($codec->hash($mailToken), $mailAccount->getRescueTokenHash());
        $this->entityManager->clear();
        $policy->change(RegistrationMode::Token);
        self::assertSame(VerifyNickOutcome::Success, $makeVerify(new InMemoryTemporaryRescueTokenStore())->handle(new VerifyNick('Mail', $mailToken, 'MAILUID', 'clientB'))->outcome);
        $legacy = RegisteredNick::createPending('Legacy', 'hash:old', 'legacy@example.test', 'en', $now->modify('+1 hour'), $now);
        $legacy->activate();
        $repo->save($legacy);
        $issued = [];
        $notifier = $this->createMock(RescueTokenNotifier::class);
        $notifier->expects(self::exactly(2))->method('issued')->willReturnCallback(static function (string $uid, string $t) use (&$issued): void {$issued[] = $t; });
        $issue = new IssueMigrationRescueTokenHandler($repo, $codec, $temp, $notifier);
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(), 'LEGACYUID', $now));
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(), 'LEGACYUID', $now));
        self::assertNull($db->fetchOne('SELECT token FROM registered_nicks WHERE id=?', [$legacy->getId()]));
        $before = $digest();
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Legacy', $issued[1], 'FOREIGN', 'clientC'))->outcome);
        self::assertSame($before, $digest());
        $sessions->register('LEGACYUID', 'Legacy');
        self::assertSame(VerifyNickOutcome::InvalidToken, $verify->handle(new VerifyNick('Legacy', $issued[0], 'LEGACYUID', 'clientC'))->outcome);
        self::assertSame($before,$digest());
        self::assertSame(VerifyNickOutcome::CredentialConfirmed,$verify->handle(new VerifyNick('Legacy',$issued[1],'LEGACYUID','clientC'))->outcome);
        $issue->handle(new IssueMigrationRescueToken($legacy->getId(),'LEGACYUID',$now));
        self::assertSame($codec->hash($issued[1]),$legacy->getRescueTokenHash());
    }
}
